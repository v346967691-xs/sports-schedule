// 取一个绰号。prefer 用于在同一场比赛里避免双方绰号撞车
function nick(name, prefer) {
  const list = NICKNAME[name];
  if (!list || !list.length) return null;
  if (prefer && list.length > 1 && list.indexOf(prefer) >= 0) return prefer;
  return list[0];
}

// 有绰号用绰号，没有就用队名 —— 标题里两者混用会显得不专业，所以按双方有无统一处理
function label(name, prefer) {
  return nick(name, prefer) || name;
}

// 双方都要有绰号才用绰号，否则都用队名（避免「银河战舰」打「埃尔切」这种半吊子）
function pairLabel(homeName, awayName) {
  const h = nick(homeName);
  const a = nick(awayName);
  if (h && a && h !== a) return [h, a];
  return [homeName, awayName];
}

// 队色：配图 prompt 用。ESPN 给的 color 有时是纯白/纯黑，画面上不好看，做一次兜底
const COLOR_FALLBACK = {
  '#ffffff': '#d8d8d8', '#000000': '#3a3a3a', '#ffff00': '#e8c400',
};

function color(hex) {
  if (!hex) return '#8a8a8a';
  return COLOR_FALLBACK[hex.toLowerCase()] || hex;
}

module.exports = { NICKNAME, nick, label, pairLabel, color };
